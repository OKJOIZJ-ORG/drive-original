import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ARTIFACT_ROLES = Object.freeze([
  'root-inventory',
  'representative-selector',
  'bounded-adapter',
  'identity-reconciler',
  'mpegts-probe'
]);

const MAX_BUNDLE_BYTES = 512 * 1024;
const FORBIDDEN_CONTENT = Object.freeze([
  /PRIVATE_(?:ID|NAME|PATH|RESOURCE|ACCOUNT|TOKEN|CONTENT|MANIFEST)_SENTINEL/i,
  /\b(?:access[_-]?token|refresh[_-]?token|authorization|cookie)\b/i,
  /\bBearer\s+/i,
  /\b(?:process\.env|env\.[A-Z_]|bindings?)\b/i,
  /Access-Control-Allow-Origin\s*[:=]\s*["']?\*/i,
  /(?:[A-Za-z]:(?:\\\\|[\\/])(?![\\/])|\/Users\/|\/home\/)/,
  /[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}/,
  /sourceMappingURL\s*=/i
]);

function fail(message) {
  throw new Error(`V2-07A browser transport: ${message}`);
}

function validateArtifact({ role, source, sourcePath }) {
  if (!ARTIFACT_ROLES.includes(role)) fail(`unsupported artifact role: ${role}`);
  const bytes = Buffer.byteLength(source, 'utf8');
  if (!bytes || bytes > MAX_BUNDLE_BYTES || source.includes('\0')) {
    fail(`invalid byte length for ${role}`);
  }
  for (const pattern of FORBIDDEN_CONTENT) {
    if (pattern.test(source)) fail(`forbidden private or bound content in ${role}`);
  }
  if (!/\.(?:m?js)$/i.test(basename(sourcePath))) fail(`artifact is not JavaScript: ${role}`);
  const sha256 = createHash('sha256').update(source, 'utf8').digest('hex');
  return Object.freeze({
    role,
    path: `/v2-07a/${role}-${sha256}.js`,
    sha256,
    byteLength: bytes,
    source
  });
}

export async function buildTransport({ artifacts, outDirectory }) {
  if (!Array.isArray(artifacts) || artifacts.length < 1 || artifacts.length > ARTIFACT_ROLES.length) {
    fail('supply one to five public artifacts');
  }
  const seenRoles = new Set();
  const seenHashes = new Set();
  const bundles = [];
  for (const artifact of artifacts) {
    if (!artifact || typeof artifact.role !== 'string' || typeof artifact.sourcePath !== 'string') {
      fail('each artifact requires a role and sourcePath');
    }
    if (seenRoles.has(artifact.role)) fail(`duplicate artifact role: ${artifact.role}`);
    seenRoles.add(artifact.role);
    const source = await readFile(resolve(artifact.sourcePath), 'utf8');
    const bundle = validateArtifact({ ...artifact, source });
    if (seenHashes.has(bundle.sha256)) fail(`duplicate artifact bytes: ${artifact.role}`);
    seenHashes.add(bundle.sha256);
    bundles.push(bundle);
  }
  bundles.sort((left, right) => left.role.localeCompare(right.role));

  const publicManifest = {
    schema: 'drive-original.v2-07a-browser-transport-redacted/1',
    candidateOrigin: 'https://drive-original-v2-candidate.drive-original-cloudflare-candidate.workers.dev',
    artifacts: bundles.map(({ role, path, sha256, byteLength }) => ({ role, path, sha256, byteLength }))
  };
  const generatedModule = [
    '// Generated by build-transport.mjs. Do not hand-edit.',
    `export const BUNDLES = Object.freeze(${JSON.stringify(bundles, null, 2)}.map((bundle) => Object.freeze(bundle)));`,
    ''
  ].join('\n');

  const output = resolve(outDirectory);
  await mkdir(output, { recursive: true });
  await writeFile(resolve(output, 'generated-bundles.mjs'), generatedModule, 'utf8');
  await writeFile(resolve(output, 'manifest.redacted.json'), `${JSON.stringify(publicManifest, null, 2)}\n`, 'utf8');
  return Object.freeze({ manifest: publicManifest, bundles: bundles.map(({ source, ...publicBundle }) => publicBundle) });
}

function parseArguments(argv) {
  const artifacts = [];
  let outDirectory = fileURLToPath(new URL('./', import.meta.url));
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--artifact') {
      const value = argv[++index];
      const delimiter = value?.indexOf('=') ?? -1;
      if (delimiter <= 0 || delimiter === value.length - 1) fail('use --artifact role=path');
      artifacts.push({ role: value.slice(0, delimiter), sourcePath: value.slice(delimiter + 1) });
    } else if (argument === '--out') {
      outDirectory = argv[++index];
      if (!outDirectory) fail('--out requires a directory');
    } else {
      fail(`unknown argument: ${argument}`);
    }
  }
  return { artifacts, outDirectory };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildTransport(parseArguments(process.argv.slice(2)));
}
